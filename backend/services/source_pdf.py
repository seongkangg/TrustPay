"""A downloadable PDF of an invoice's source document, rebuilt from its masked text.

The original file is never kept, and it would carry raw bank / routing / tax numbers, so this is a
masked copy: the text read from the source (`Invoice.source_text`, masked at ingestion and again
when served) laid out on a page, with a header saying what it is.
"""

from fpdf import FPDF

from backend.models import Invoice
from backend.utils.timestamps import now_utc


def _latin1(text: str) -> str:
    # The built-in PDF fonts cover Latin-1 only; anything else prints as "?" rather than failing.
    return text.encode("latin-1", "replace").decode("latin-1")


def render_masked_pdf(invoice: Invoice) -> bytes:
    """One masked-copy PDF for `invoice`; the caller checks that `source_text` is present."""
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 15)
    pdf.cell(
        0,
        8,
        _latin1(f"{invoice.invoice_id} - source document (masked copy)"),
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.set_font("Helvetica", size=9)
    pdf.set_text_color(107, 111, 123)
    lines = [
        f"Source: {invoice.source_document or 'unknown'}",
        f"Generated by TrustPay {now_utc().strftime('%Y-%m-%d %H:%M UTC')}. Rebuilt from the text read "
        "from the source; bank, routing and tax numbers are masked. This is not the original file.",
    ]
    for line in lines:
        pdf.multi_cell(0, 4.5, _latin1(line), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(3)
    pdf.set_draw_color(220, 221, 227)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(5)

    pdf.set_font("Helvetica", size=11)
    for line in (invoice.source_text or "").replace("\r", "").split("\n"):
        pdf.multi_cell(0, 5.5, _latin1(line) or " ", new_x="LMARGIN", new_y="NEXT")

    return bytes(pdf.output())
